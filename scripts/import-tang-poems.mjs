// Build the built-in 《唐詩三百首》 content pack for 聽&說.
//
//   node scripts/import-tang-poems.mjs [path/to/唐诗三百首.json] [translations.json]
//
// Source: chinese-poetry (MIT) 全唐诗/唐诗三百首.json — Traditional Chinese,
// one array of { author, title, paragraphs[], tags[] }. Poems are grouped into
// sets by form (五言絕句 / 七言絕句 / …); every couplet ("paragraph") becomes one
// item labelled "<title> · <author> ①". Optional translations.json maps
// "<title>|<author>" → array of English lines (one per couplet) — Witter
// Bynner's public-domain 1929 renderings where we have them; authors can add
// the rest in the editor.
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] || resolve(here, '../../scratch/tang300.json'));
const trPath = process.argv[3] ? resolve(process.argv[3]) : null;
const poems = JSON.parse(readFileSync(src, 'utf8'));
const translations = trPath ? JSON.parse(readFileSync(trPath, 'utf8')) : {};

const FORMS = [
  ['五言绝句', 'wuyan-jueju', '五言絕句', 'Five-character quatrains'],
  ['七言绝句', 'qiyan-jueju', '七言絕句', 'Seven-character quatrains'],
  ['五言律诗', 'wuyan-lushi', '五言律詩', 'Five-character regulated verse'],
  ['七言律诗', 'qiyan-lushi', '七言律詩', 'Seven-character regulated verse'],
  ['五言古诗', 'wuyan-gushi', '五言古詩', 'Five-character old-style poems'],
  ['七言古诗', 'qiyan-gushi', '七言古詩', 'Seven-character old-style poems'],
  ['乐府', 'yuefu', '樂府', 'Yuefu ballads'],
];
const CIRCLED = '①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳';
const circ = (i) => CIRCLED[i] || `(${i + 1})`;
const cleanTitle = (t) => String(t).replace(/^(鼓吹曲辭|橫吹曲辭|相和歌辭|雜曲歌辭|琴曲歌辭|新樂府辭|近代曲辭|雜歌謠辭|輞川集)\s+/, '').trim();

const groups = new Map(FORMS.map(f => [f[0], []]));
const other = [];
for (const p of poems) {
  const f = FORMS.find(f => (p.tags || []).includes(f[0]));
  (f ? groups.get(f[0]) : other).push(p);
}
const buildSet = (id, title, titleEn, list, desc) => ({
  id: `tang300-${id}`,
  title,
  titleEn,
  description: desc,
  language: 'cuv',
  sourceLang: 'zh',
  builtIn: true,
  verses: list.flatMap((p) => {
    const t = cleanTitle(p.title);
    const tr = translations[`${t}|${p.author}`] || translations[`${p.title}|${p.author}`] || [];
    return p.paragraphs.map((para, i) => ({
      reference: `${t} · ${p.author} ${circ(i)}`,
      text: para,
      textEn: tr[i] || '',
      poem: t,
      author: p.author,
    }));
  }),
});
const sets = FORMS.map(([tag, id, zh, en]) => buildSet(id, `唐詩三百首・${zh}`, `300 Tang Poems · ${en}`, groups.get(tag),
  `《唐詩三百首》${zh}，共 ${groups.get(tag).length} 首。每一段是一聯，可以聽、跟讀、錄音、挑戰。`));
if (other.length) sets.push(buildSet('other', '唐詩三百首・其他', '300 Tang Poems · Others', other, `《唐詩三百首》其他體裁，共 ${other.length} 首。`));

const out = resolve(here, '../src/content/tangPoems.js');
mkdirSync(dirname(out), { recursive: true });
const withTr = sets.reduce((n, s) => n + s.verses.filter(v => v.textEn).length, 0);
writeFileSync(out, `// AUTO-GENERATED by scripts/import-tang-poems.mjs — do not edit by hand.
// 《唐詩三百首》 from chinese-poetry (MIT); English lines (where present) from
// Witter Bynner, The Jade Mountain (1929, public domain).
export const TANG_POEM_SETS = ${JSON.stringify(sets, null, 1)};
`);
console.log('sets:', sets.map(s => `${s.title} (${s.verses.length} items)`).join(', '));
console.log('items with English:', withTr, '→', out);
